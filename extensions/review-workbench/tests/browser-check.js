// Run with playwright-cli run-code --filename extensions/review-workbench/tests/browser-check.js
// Requires the demo on 4192 and an ISOLATED Agentation server on 4760, not your live server.
async page => {
  const check=(value,message)=>{if(!value)throw Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(10000);
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:4192/?endpoint=http://127.0.0.1:4760');
  await page.getByRole('button',{name:'Start feedback mode',exact:true}).waitFor();
  await page.keyboard.press('Meta+Shift+F');
  await page.getByRole('button',{name:'Rectangle mode',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Review Workbench',exact:true}).click();
  const draft=page.getByPlaceholder('What should change?');
  await draft.fill('Workbench isolated connection test');
  await page.getByRole('button',{name:/^Comments ·/}).click();
  check(await draft.isVisible(),'Opening the list must not discard an active comment draft');
  check(await draft.inputValue()==='Workbench isolated connection test','Draft text must be preserved');
  await draft.press('Meta+Shift+F');
  check(await draft.isVisible(),'The mode shortcut must not close a draft while typing');
  await draft.press('Meta+Enter');
  await draft.waitFor({state:'hidden'});
  await page.getByRole('button',{name:/^Comments ·/}).click();
  const row=page.locator('.agw-panel li').filter({hasText:'Workbench isolated connection test'});
  await row.waitFor();
  const sessions=await (await page.request.get('http://127.0.0.1:4760/sessions')).json();
  const records=(await Promise.all(sessions.map(async s=>(await page.request.get('http://127.0.0.1:4760/sessions/'+s.id)).json()))).flatMap(s=>s.annotations);
  check(records.some(n=>n.comment==='Workbench isolated connection test'&&n.url.startsWith('http://127.0.0.1:4192/')),'The exact note and page must reach the isolated real server');
  await row.getByRole('button',{name:'Mark applied',exact:true}).click();
  await row.locator('.agw-applied').waitFor();
  await page.screenshot({path:'output/playwright/review-workbench-1440.png'});
  await row.getByRole('button',{name:'Delete',exact:true}).click();
  check(await row.getByRole('button',{name:'Cancel',exact:true}).evaluate(el=>el===document.activeElement),'Cancel must get default focus');
  await row.getByRole('button',{name:'Cancel',exact:true}).click();
  check(await row.isVisible(),'Cancel must preserve the comment');
  await page.route('http://127.0.0.1:4760/annotations/**',async route=>{
    if(route.request().method()==='DELETE')return route.fulfill({status:503,body:'synthetic failure',headers:{'Access-Control-Allow-Origin':'http://127.0.0.1:4192'}});
    return route.continue();
  },{times:1});
  await row.getByRole('button',{name:'Delete',exact:true}).click();
  await row.getByRole('button',{name:'Delete comment',exact:true}).click();
  await page.getByRole('alert').waitFor();
  check(await row.isVisible(),'A failed delete must preserve the comment');
  await page.waitForTimeout(2700);
  check(await page.getByRole('alert').isVisible(),'Polling must not erase a deletion failure');
  await row.getByRole('button',{name:'Delete comment',exact:true}).click();
  await row.waitFor({state:'detached'});
  await page.reload();
  await page.getByRole('button',{name:/^Comments ·/}).click();
  await page.getByText('No comments yet. Click or drag in feedback mode to add one.').waitFor();
  await page.getByRole('button',{name:'Close comments',exact:true}).click();
  await page.keyboard.press('Meta+Shift+F');
  await page.getByRole('button',{name:'Edit text',exact:true}).click();
  await page.getByRole('textbox',{name:'Title',exact:true}).fill('Edited in the public extension demo');
  await page.getByRole('button',{name:'Save sample',exact:true}).click();
  await page.reload();
  await page.getByRole('heading',{name:'Edited in the public extension demo',exact:true}).waitFor();
  await page.keyboard.press('Meta+Shift+F');
  await page.getByRole('button',{name:'Drawesome',exact:true}).click();
  const drawing=page.locator('.draw-editor');await drawing.waitFor();
  const box=await drawing.boundingBox();
  await page.mouse.move(box.x+60,box.y+50);await page.mouse.down();await page.mouse.move(box.x+220,box.y+90,{steps:12});await page.mouse.up();
  await page.screenshot({path:'output/playwright/review-workbench-draw.png'});
  await page.getByRole('button',{name:'Save sample',exact:true}).click();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('agentation-workbench-demo-v1')));
  check(saved.strokes.length>0,'Drawing strokes must save in the sample adapter');
  await page.reload();
  check(await page.getByRole('img',{name:'Saved sample drawing'}).getAttribute('src').then(src=>src.length>300),'Saved drawing must render on reload');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:/^Comments ·/}).click();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390px view must not overflow horizontally');
  await page.getByRole('button',{name:'Close comments',exact:true}).click();
  await page.keyboard.press('Meta+Shift+F');
  await page.getByRole('button',{name:'Edit text',exact:true}).click();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'The narrow text editor must not overflow');
  await page.getByRole('textbox',{name:'Title',exact:true}).fill('Narrow editor sample');
  await page.getByRole('button',{name:'Save sample',exact:true}).click();
  await page.locator('agentation-toolbar').evaluate(async host=>{
    await Promise.all(host.shadowRoot.getAnimations({subtree:true}).filter(a=>Number.isFinite(a.effect?.getComputedTiming().endTime)).map(a=>a.finished.catch(()=>{})));
  });
  await page.waitForTimeout(250);
  await page.screenshot({path:'output/playwright/review-workbench-390.png'});
  check(errors.length===0,'Browser errors: '+errors.join('; '));
  return {passed:true,widths:[1440,390],realIsolatedServer:true,shortcuts:true,draftProtection:true,applied:true,deleteCancel:true,deleteRetry:true,noResurrection:true,textPersisted:true,drawingPersisted:true};
}
